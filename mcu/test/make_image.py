"""Turn a black-and-white image into mcu/src/image_data.h for SHOW_IMAGE.

Black (dark) pixels become ink. The image is scaled to fit the display
(IMG_W x IMG_H, with a margin) and stored 1 bit per pixel, MSB first, rows
padded to whole bytes. image_data.h is gitignored, so a picture used for a
demo stays out of the repo.

  python make_image.py picture.png [--height 1000]
"""

import argparse
import pathlib

from PIL import Image

IMG_W, IMG_H = 1440, 1072

ap = argparse.ArgumentParser()
ap.add_argument('image')
ap.add_argument('--height', type=int, default=1000, help='target height in pixels')
a = ap.parse_args()

im = Image.open(a.image).convert('L')
scale = min(a.height / im.height, (IMG_W - 40) / im.width)
im = im.resize((round(im.width * scale), round(im.height * scale)), Image.LANCZOS)
w, h = im.size
px = im.load()
row_bytes = (w + 7) // 8
data = bytearray(row_bytes * h)
for y in range(h):
    for x in range(w):
        if px[x, y] < 128:
            data[y * row_bytes + x // 8] |= 0x80 >> (x % 8)

out = pathlib.Path(__file__).resolve().parents[1] / 'src' / 'image_data.h'
lines = [f'// generated by mcu/test/make_image.py from {pathlib.Path(a.image).name}',
         f'#define IMAGE_W {w}', f'#define IMAGE_H {h}',
         'static const unsigned char image_bits[] = {']
for i in range(0, len(data), 24):
    lines.append('    ' + ','.join(str(b) for b in data[i:i + 24]) + ',')
lines.append('};')
out.write_text('\n'.join(lines) + '\n')
print(f'{w} x {h}, {len(data)} bytes -> {out}')
